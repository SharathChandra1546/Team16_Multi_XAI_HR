// Checks the production build: no secrets, no generator tags, size budgets, required launch files.
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

const DIST = "dist";
const files = [];
(function walk(d) {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    statSync(p).isDirectory() ? walk(p) : files.push(p);
  }
})(DIST);

const problems = [];
const secretPatterns = [/AIza[0-9A-Za-z_-]{30,}/, /\bsk-[A-Za-z0-9]{20,}/, /\bgsk_[A-Za-z0-9]{20,}/, /GEMINI_API_KEY|OPENAI_API_KEY|GROQ_API_KEY|ADMIN_TOKEN/];
const tagPatterns = [/made with (ai|claude|chatgpt|gpt|v0|lovable|bolt)/i, /generated by (ai|claude|chatgpt)/i, /<meta name="generator"/i];
let js = 0;
for (const f of files) {
  const size = statSync(f).size;
  if (/\.(js|css|html|xml|txt|svg)$/.test(f)) {
    const text = readFileSync(f, "utf8");
    for (const p of secretPatterns) if (p.test(text)) problems.push(`possible secret in ${f}: ${p}`);
    for (const p of tagPatterns) if (p.test(text)) problems.push(`generator tag in ${f}: ${p}`);
  }
  if (f.endsWith(".js")) js += size;
  if (/\.(png|jpe?g|webp)$/.test(f) && size > 200_000) problems.push(`image over 200 KB: ${f}`);
}
for (const req of ["index.html", "404.html", "favicon.svg", "favicon-32.png", "og-image.png", "robots.txt", "sitemap.xml"]) {
  if (!files.includes(join(DIST, req))) problems.push(`missing ${req}`);
}
if (js > 350_000) problems.push(`JavaScript is ${Math.round(js / 1000)} KB (budget 350 KB)`);
if (problems.length) {
  console.error("Build checks failed:\n- " + problems.join("\n- "));
  process.exit(1);
}
console.log(`Build checks passed: ${files.length} files, JavaScript ${Math.round(js / 1000)} KB.`);
